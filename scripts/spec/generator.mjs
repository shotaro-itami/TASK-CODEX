function markdownCell(value) {
  return String(value ?? "").replaceAll("|", "\\|").replaceAll("\n", "<br>");
}

function table(records, columns) {
  const headings = columns.map(([heading]) => heading);
  const keys = columns.map(([, key]) => key);
  const rows = records.map((record) => keys.map((key) => markdownCell(record[key])));
  return [headings, headings.map(() => "---"), ...rows].map((row) => `| ${row.join(" | ")} |`).join("\n");
}

function containsAny(record, expression) {
  return expression.test(record.values.join("\n"));
}

function selectDocumentRows(catalog, kind) {
  const predicate = kind === "content-management"
    ? /教材|コンテンツ|データ|Qualification|Syllabus|Domain|Topic|Concept|Question/u
    : /教材|AI|AWS|source|取得|正規化|Content pipeline|Concept|Question/iu;
  const req = new Set(catalog.reqRows.filter((row) => containsAny(row, predicate)).map((row) => row.ID));
  const bas = new Set(catalog.basRows.filter((row) => containsAny(row, predicate) || parseIdList(row["関連要件"], "REQ").some((id) => req.has(id))).map((row) => row.ID));
  for (const row of catalog.basRows) if (bas.has(row.ID)) for (const id of parseIdList(row["関連要件"], "REQ")) req.add(id);
  const det = new Set(catalog.detRows.filter((row) => containsAny(row, predicate) || parseIdList(row["関連基本設計"], "BAS").some((id) => bas.has(id))).map((row) => row.ID));
  for (const row of catalog.detRows) if (det.has(row.ID)) for (const id of parseIdList(row["関連基本設計"], "BAS")) bas.add(id);
  return {
    reqRows: catalog.reqRows.filter((row) => req.has(row.ID)),
    basRows: catalog.basRows.filter((row) => bas.has(row.ID)),
    detRows: catalog.detRows.filter((row) => det.has(row.ID)),
  };
}

